# Verify central dispatcher callsites directly against both block images.
checks=[]
for state, addrset, getter8, getter16 in [
    ('old', {r['id']:r['old'] for r in rows}, 0x149b0cc, 0x149b18c),
    ('new', {r['id']:r['new'] for r in rows}, 0x14920fc, 0x14921bc),
]:
    b = load('X-H2', state, 1)
    for row in rows:
        for site in addrset[row['id']]:
            site_i = int(site, 16)
            before = dis(b, site_i-8, 3)
            expected = row['id'].lower()
            assert expected in before.lower(), (state, row['id'], site, before)
            getter = getter8 if row['type']=='u8' else getter16
            assert f'bl #0x{getter:x}' in dis(b, site_i, 1).lower(), (state,row['id'],site)
            checks.append({'версия':state,'id':row['id'],'адрес':site,'тип':'u8' if row['type']=='u8' else 'u16','проверка':'непосредственная инструкция mov ID и BL к геттеру'})

