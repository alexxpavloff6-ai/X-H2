def immediate(op):
    m = re.search(r'#(-?0x[0-9a-fA-F]+|-?\d+)', op)
    return int(m.group(1), 0) if m else None


def mem_sp(op):
    m = re.search(r'\[sp, #(0x[0-9a-fA-F]+|\d+)\]', op)
    return int(m.group(1), 0) if m else None


def parse_publication(pub, record_id):
    f = int(pub['function'], 16)
    site = int(pub['site'], 16)
    ins = insns(B0, f, max(1, (site - f) // 4 + 1))
    code = header_off = None
    for a, b in zip(ins, ins[1:]):
        if a.mnemonic == 'mov' and a.op_str.startswith('w0, #') and b.mnemonic == 'strh' and b.op_str.startswith('w0, [sp, #'):
            val = immediate(a.op_str)
            off = mem_sp(b.op_str)
            if val is not None and 0x1000 <= val <= 0x1fff and off is not None:
                code, header_off = val, off
                break
    length = payload_off = None
    if header_off is not None:
        for a, b in zip(ins, ins[1:]):
            if a.mnemonic == 'mov' and a.op_str.startswith('w0, #') and b.mnemonic == 'str' and mem_sp(b.op_str) == header_off + 4:
                length = immediate(a.op_str)
            if a.mnemonic == 'add' and re.match(r'x0, sp, #', a.op_str) and b.mnemonic == 'str' and b.op_str.startswith('x0, [sp, #') and mem_sp(b.op_str) == header_off + 8:
                payload_off = immediate(a.op_str)

    ptr = {'x0': ('arg0', 0), 'w0': ('arg0', 0), 'x1': ('arg1', 0), 'w1': ('arg1', 0)}
    val = {'x0': 'значение arg0', 'w0': 'значение arg0', 'x1': 'значение arg1', 'w1': 'значение arg1'}
    stack_ptr = {}
    reads = []
    writes = []
    zero_ranges = []

    for idx, i in enumerate(ins):
        op = i.op_str
        if i.mnemonic == 'mov':
            m = re.fullmatch(r'(x\d+|w\d+), (x\d+|w\d+)', op)
            if m:
                dst, src = m.group(1), m.group(2)
                if src in ptr:
                    ptr[dst] = ptr[src]
                else:
                    ptr.pop(dst, None)
                if src in val:
                    val[dst] = val[src]
                else:
                    val[dst] = f'значение {src}'
                if src in stack_ptr:
                    stack_ptr[dst] = stack_ptr[src]
                else:
                    stack_ptr.pop(dst, None)
                continue
            m = re.fullmatch(r'(x\d+|w\d+), #(-?0x[0-9a-fA-F]+|-?\d+)', op)
            if m:
                dst, n = m.group(1), int(m.group(2), 0)
                ptr.pop(dst, None); stack_ptr.pop(dst, None)
                val[dst] = f'константа {n:#x}'
                continue
        if i.mnemonic == 'add':
            m = re.fullmatch(r'(x\d+|w\d+), sp, #(0x[0-9a-fA-F]+|\d+)', op)
            if m:
                dst, off = m.group(1), int(m.group(2), 0)
                stack_ptr[dst] = off
                ptr.pop(dst, None)
                val[dst] = f'адрес стека +{off:#x}'
                continue
            m = re.fullmatch(r'(x\d+|w\d+), (x\d+|w\d+), #(0x[0-9a-fA-F]+|\d+)', op)
            if m and m.group(2) in ptr:
                dst, src, off = m.group(1), m.group(2), int(m.group(3), 0)
                base_name, base_off = ptr[src]
                ptr[dst] = (base_name, base_off + off)
                val[dst] = f'указатель {base_name}+{base_off + off:#x}'
                continue
        if i.mnemonic.startswith('ldr'):
            m = re.match(r'(x\d+|w\d+), \[(x\d+|w\d+)(?:, #(0x[0-9a-fA-F]+|\d+))?\]', op)
            if m:
                dst, base = m.group(1), m.group(2)
                off = int(m.group(3), 0) if m.group(3) else 0
                width = 'u8' if i.mnemonic.endswith('b') else 'u16' if i.mnemonic.endswith('h') else 'u64' if dst.startswith('x') else 'u32'
                if base in ptr:
                    arg, base_off = ptr[base]
                    total = base_off + off
                    reads.append({'аргумент': arg, 'смещение': total, 'ширина': width})
                    val[dst] = f'{arg}+{total:#x}:{width}'
                    ptr.pop(dst, None); stack_ptr.pop(dst, None)
                elif base in stack_ptr:
                    val[dst] = f'стек+{stack_ptr[base] + off:#x}:{width}'
                    ptr.pop(dst, None); stack_ptr.pop(dst, None)
                else:
                    val[dst] = f'неустановленное чтение {base}+{off:#x}:{width}'
                    ptr.pop(dst, None); stack_ptr.pop(dst, None)
                continue
        if i.mnemonic in ('bfi', 'bfxil', 'ubfx', 'sbfiz', 'and', 'orr', 'eor', 'lsl', 'lsr', 'asr', 'ubfiz'):
            ops = [x.strip() for x in op.split(',')]
            if ops and re.fullmatch(r'(x|w)\d+', ops[0]):
                dst = ops[0]
                src_regs = [x for x in ops[1:] if re.fullmatch(r'(x|w)\d+', x)]
                src_desc = ','.join(val.get(x, x) for x in src_regs)
                val[dst] = f'{i.mnemonic}({src_desc})' if src_desc else f'{i.mnemonic}({op})'
                ptr.pop(dst, None); stack_ptr.pop(dst, None)
        if payload_off is not None and length is not None and i.mnemonic in ('strb', 'strh', 'str', 'stp'):
            m = re.match(r'(\w+)(?:, (\w+))?, \[sp, #(0x[0-9a-fA-F]+|\d+)\]', op)
            if m:
                off = int(m.group(3), 0)
                if payload_off <= off < payload_off + length:
                    src1, src2 = m.group(1), m.group(2)
                    source = (f'указатель {ptr[src1][0]}+{ptr[src1][1]:#x}' if src1 in ptr else val.get(src1, src1))
                    if src2:
                        source += '; ' + (f'указатель {ptr[src2][0]}+{ptr[src2][1]:#x}' if src2 in ptr else val.get(src2, src2))
                    width = {'strb': 'u8', 'strh': 'u16', 'str': 'u32/u64' if src1.startswith('x') else 'u32', 'stp': 'pair'}[i.mnemonic]
                    writes.append({'смещение_пакета': off - payload_off, 'ширина': width, 'источник': source})
        if i.mnemonic == 'bl' and i.op_str.strip() == '#0x14d2704' and idx >= 3:
            a0, a1, a2 = ins[idx - 3:idx]
            baseoff = stack_ptr.get(a0.op_str.split(',')[0]) if a0.mnemonic == 'add' else None
            fill = immediate(a1.op_str) if a1.mnemonic == 'mov' else None
            count = immediate(a2.op_str) if a2.mnemonic == 'mov' else None
            if baseoff is not None and count is not None and payload_off is not None and payload_off <= baseoff < payload_off + (length or 0):
                zero_ranges.append({'смещение_пакета': baseoff - payload_off, 'байт': count * 4, 'заполнение': fill})

    unique_reads = []
    seen = set()
    for r in reads:
        key = (r['аргумент'], r['смещение'], r['ширина'])
        if key not in seen:
            seen.add(key); unique_reads.append(r)
    unique_writes = []
    seen = set()
    for w in writes:
        key = (w['смещение_пакета'], w['ширина'], w['источник'])
        if key not in seen:
            seen.add(key); unique_writes.append(w)
    return {
        'запись': record_id,
        'код': code,
        'функция': f'{f:#x}',
        'сайт_публикации': f'{site:#x}',
        'длина_данных': length,
        'смещение_данных_в_стеке': payload_off,
        'чтения_из_аргументов': unique_reads,
        'записи_в_данные': unique_writes,
        'нулевые_области': zero_ranges,
        'сайт_прямого_вызова': [],
    }


def lens_classifier(code):
    if code == 0x18d7: return 2
    if code == 0x18d8: return 3
    if 0x18d9 <= code <= 0x1932: return 4
    if code == 0x1933: return 5
    if code == 0x1934: return 7
    if code == 0x1935: return 8
    if code == 0x1936: return 9
    if code == 0x1937: return 10
    if 0x1938 <= code <= 0x1944: return 4
    return 0


def lens_jump_target(code):
    if not 0x18d9 <= code <= 0x1944:
        return None
    idx = code - 0x18d9
    tab_off = B0.off(0x1912414) + 2 * idx
    rel = struct.unpack_from('<h', B0.data, tab_off)[0]
    return 0x13ebbec + rel * 4


def lens_route(code, target):
    if code == 0x191a:
        return 'особая ветвь 0x13EB4DC: ожидание события 0xE0001 и обратный вызов'
    cat = lens_classifier(code)
    if cat == 2: return 'категория 2 -> 0x13E6158'
    if cat == 3: return 'категория 3 -> в строке таблицы функции нет'
    if cat == 4:
        if target == 0x13ebbec: return 'категория 4 -> 0x13EC520 -> 0x13EBB88; общий ход без отдельного разбора полей'
        return f'категория 4 -> 0x13EC520 -> 0x13EBB88 -> {target:#x}'
    if cat == 5: return 'категория 5 -> в строке таблицы функции нет'
    if cat in (7, 9): return f'категория {cat} -> 0x13E54CC'
    if cat in (8, 10): return f'категория {cat} -> в строке таблицы функции нет'
    return f'категория {cat}; для кода нет подтверждённого перехода к разборщику'


def compact_fields(p):
    reads = p['чтения_из_аргументов']
    reads_txt = []
    for r in reads:
        reads_txt.append(f"{r['аргумент']}+{r['смещение']:#x}:{r['ширина']}")
    offs = []
    for w in p['записи_в_данные']:
        offs.append(f"+{w['смещение_пакета']:#x}")
    pointer_writes = []
    for w in p['записи_в_данные']:
        src = w['источник']
        if src.startswith('указатель '):
            pointer_writes.append(f"+{w['смещение_пакета']:#x} <- {src}")
    detail = []
    if reads_txt:
        detail.append('чтение ' + ', '.join(reads_txt))
    if pointer_writes:
        detail.append('указатели ' + ', '.join(pointer_writes))
    if offs:
        detail.append('записи в ' + ', '.join(dict.fromkeys(offs)))
    if not detail:
        detail.append('явные источники полей не выделены')
    return '; '.join(detail)


