from fwcommon import load, bl_callers, adrp_refs  # noqa: E402

model, state = "X-H2", "old"
block1 = load(model, state, 1)
blocks = [load(model, state, i) for i in (0, 1, 2)]

def xrefs(target):
    return [{"адрес": hex(site), "вид": kind} for site, kind in bl_callers(block1, target)]

mmio_pages = [0xFF914000, 0xFF915000, 0xFF911000, 0xFF913000, 0xFF90E100, 0xFF976000]
mmio = {}
for address in mmio_pages:
    hits = []
    for index, block in enumerate(blocks):
        for row in adrp_refs(block, address, window=25):
            hits.append({"блок": index, "адрес": hex(row["site"]), "инструкция": row["insn"]})
    mmio[hex(address)] = hits

